function splitName(name: string): string[] {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').split(/[_\s]+/).filter(Boolean).map((item) => item.toLowerCase());
}

export function getFieldLabel(name: string): string {
  const key = name.toLowerCase();
  if (commonFieldLabels[key]) return commonFieldLabels[key];
  const tokens = splitName(name);
  const translated = tokens.map((token) => tokenLabels[token] ?? token).join('');
  return translated || '业务信息';
}

export function getEnumLabel(value: string): string {
  return enumLabels[value] ?? value;
}

export function getFieldKind(name: string): PresentationKind {
  const key = name.toLowerCase();
  if (key.includes('date') || key.endsWith('_at')) return key.includes('time') || key.endsWith('_at') ? 'time' : 'date';
  if (key === 'status' || key.endsWith('_status')) return 'status';
  if (key.includes('amount') || key.includes('price') || key.includes('cost') || key.includes('salary') || key.includes('balance')) return 'currency';
  if (key.includes('quantity') || key.includes('qty') || key.includes('count') || key.includes('hours') || key.includes('days') || key.includes('age') || key.includes('weight')) return 'number';
  if (key === 'archived' || key === 'executed' || key === 'qualified' || key === 'overdue' || key === 'signed') return 'boolean';
  return 'text';
}

export function getColumnWidth(name: string): number {
  const kind = getFieldKind(name);
  if (name === 'id' || name.endsWith('_id')) return 90;
  if (kind === 'date' || kind === 'time') return 170;
  if (kind === 'currency' || kind === 'number') return 130;
  if (kind === 'status') return 110;
  if (name === 'remark' || name.includes('address') || name.includes('content')) return 200;
  return 140;
}

export function formatDisplayValue(value: unknown, fieldName?: string): string {
  if (value === null || value === undefined || value === '') return '—';
  if (typeof value === 'boolean') return value ? '是' : '否';
  if (typeof value === 'object') return JSON.stringify(value);
  let text: string;
  if (typeof value === 'string') text = value;
  else if (typeof value === 'number' || typeof value === 'boolean' || typeof value === 'bigint') text = String(value);
  else if (typeof value === 'symbol') text = value.description ?? '—';
  else text = '—';
  if (fieldName && getFieldKind(fieldName) === 'status') return getEnumLabel(text);
  if (fieldName && (getFieldKind(fieldName) === 'date' || getFieldKind(fieldName) === 'time')) {
    const date = new Date(text);
    if (!Number.isNaN(date.getTime()) && /^\d{4}-\d{2}-\d{2}/.test(text)) {
      return text.length > 10 ? text.replace('T', ' ').slice(0, 19) : text;
    }
  }
  return text;
}
