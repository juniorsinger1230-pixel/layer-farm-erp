import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = fileURLToPath(new URL('../', import.meta.url));
const designRoot = join(appRoot, '..', '..', '..');
const tableSource = '数据库与数据设计_活动②_表结构与索引设计_V1.0.0/table-index-structure-catalog.json';
const dictionarySource = '数据库与数据设计_活动③_数据字典编制_V1.0.0/data-dictionary-catalog.json';
const readJson = (relative) => JSON.parse(readFileSync(join(designRoot, relative), 'utf8'));
const digest = (value) => createHash('sha256').update(value).digest('hex');
const tablesModel = readJson(tableSource);
const dictionaryModel = readJson(dictionarySource);
const tables = tablesModel.tableStructureContracts;
const dictionary = dictionaryModel.columnDictionaryEntries;
const normalizations = [];
const q = (identifier) => {
  if (!/^[a-z][a-z0-9_]*$/.test(identifier)) throw new Error(`Unsafe SQL identifier: ${identifier}`);
  return `"${identifier}"`;
};
const columns = (names) => names.map(q).join(', ');
const tableById = new Map(tables.map((table) => [table.tableId, table]));
const dictionaryByTable = new Map(dictionaryModel.tableDictionaryEntries.map((entry) => [entry.tableId, entry]));

function normalizeDefault(table, column) {
  const value = column.defaultValue;
  if (value === null) return '';
  if (value === 'GENERATED_IDENTITY_PENDING_DDL') {
    if (column.dataType !== 'BIGINT') throw new Error(`Identity must be BIGINT: ${table.tableName}.${column.columnName}`);
    return ' GENERATED BY DEFAULT AS IDENTITY';
  }
  if (value === 'CURRENT_ACTOR_CONTEXT_PENDING_DDL') {
    normalizations.push({ kind: 'ACTOR_CONTEXT_DEFAULT', table: table.tableName, column: column.columnName, source: value });
    return " DEFAULT nullif(current_setting('app.actor_id', true), '')";
  }
  if (value === 'now()' || /^CURRENT_TIMESTAMP$/i.test(value) || /^\d+(?:\.\d+)?$/.test(value) || /^(?:true|false)$/i.test(value) || /^'.*'$/.test(value)) {
    return ` DEFAULT ${value}`;
  }
  if (['NOT_STARTED', 'v1'].includes(value)) {
    normalizations.push({ kind: 'QUOTED_STRING_DEFAULT', table: table.tableName, column: column.columnName, source: value });
    return ` DEFAULT '${value}'`;
  }
  // 来源模型把 CHECK/UNIQUE/FK/系统推算填进了 defaultValue；它们不是合法默认值。
  normalizations.push({ kind: 'NON_DEFAULT_SOURCE_TEXT_REMOVED', table: table.tableName, column: column.columnName, source: value });
  return '';
}

function normalizeCheck(table, contract) {
  let expression = contract.expression;
  if (/^0\s*<=\s*([a-z][a-z0-9_]*)\s*<=\s*100$/.test(expression)) {
    const column = expression.match(/^0\s*<=\s*([a-z][a-z0-9_]*)\s*<=\s*100$/)[1];
    expression = `(${column} >= 0 AND ${column} <= 100)`;
    normalizations.push({ kind: 'SQL_CHAINED_COMPARISON_EXPANDED', table: table.tableName, constraint: contract.constraintName });
  }
  const available = new Set(table.columns.map((column) => column.columnName));
  const referenced = [...expression.matchAll(/[a-z][a-z0-9_]*/g)].map((match) => match[0])
    .filter((token) => !['and', 'or', 'not', 'is', 'null', 'true', 'false', 'current_setting'].includes(token));
  const missing = [...new Set(referenced.filter((name) => !available.has(name)))];
  if (missing.length > 0) {
    // payable 模型引用不存在的 gross_amount；保留可执行的非负约束，并把跨字段校验留给财务应用层。
    expression = expression.split(/\s+AND\s+/i).filter((part) => !missing.some((name) => new RegExp(`\\b${name}\\b`).test(part))).join(' AND ');
    normalizations.push({ kind: 'MISSING_COLUMN_CHECK_CLAUSE_DEFERRED_TO_APPLICATION', table: table.tableName, constraint: contract.constraintName, missingColumns: missing, executableExpression: expression });
  }
  for (const name of available) {
    expression = expression.replace(new RegExp(`\\b${name}\\b`, 'g'), q(name));
  }
  if (!expression.trim()) throw new Error(`Empty check after normalization: ${contract.constraintName}`);
  return expression;
}

const schemaSql = [
  '-- GENERATED FROM APPROVED DB-A2/DB-A3 MODELS. DO NOT HAND EDIT.',
  `-- Source SHA-256: ${digest(readFileSync(join(designRoot, tableSource), 'utf8'))}`,
  'CREATE SCHEMA IF NOT EXISTS app;',
  'SET search_path = app, public;',
  '',
];
for (const table of tables) {
  const defs = table.columns.map((column) => {
    const identity = column.defaultValue === 'GENERATED_IDENTITY_PENDING_DDL' ? ' GENERATED BY DEFAULT AS IDENTITY' : '';
    const normalized = identity ? '' : normalizeDefault(table, column);
    return `  ${q(column.columnName)} ${column.dataType}${identity}${normalized}${column.nullable ? '' : ' NOT NULL'}`;
  });
  defs.push(`  CONSTRAINT ${q(table.primaryKey.constraintName)} PRIMARY KEY (${columns(table.primaryKey.columns)})`);
  schemaSql.push(`CREATE TABLE IF NOT EXISTS app.${q(table.tableName)} (\n${defs.join(',\n')}\n);`, '');
}

const constraintSql = ['-- Constraints and company isolation. Transactions required.', 'SET search_path = app, public;', ''];
for (const contract of tablesModel.uniqueConstraintContracts) {
  const table = tableById.get(contract.tableId);
  constraintSql.push(`ALTER TABLE app.${q(table.tableName)} ADD CONSTRAINT ${q(contract.constraintName)} UNIQUE (${columns(contract.columns)});`);
}
for (const contract of tablesModel.checkConstraintContracts) {
  const table = tableById.get(contract.tableId);
  constraintSql.push(`ALTER TABLE app.${q(table.tableName)} ADD CONSTRAINT ${q(contract.constraintName)} CHECK (${normalizeCheck(table, contract)});`);
}
constraintSql.push('');
for (const table of tables) {
  if (!table.companyScope || !table.columns.some((column) => column.columnName === 'company_code')) continue;
  const name = q(table.tableName);
  const companyColumn = table.columns.find((column) => column.columnName === 'company_code');
  const policy = companyColumn.dataType === 'BIGINT'
    ? `current_setting('app.company_code', true) = '*' OR "company_code"::text = current_setting('app.company_id', true)`
    : `current_setting('app.company_code', true) = '*' OR "company_code" = current_setting('app.company_code', true)`;
  constraintSql.push(`ALTER TABLE app.${name} ENABLE ROW LEVEL SECURITY;`);
  constraintSql.push(`ALTER TABLE app.${name} FORCE ROW LEVEL SECURITY;`);
  constraintSql.push(`CREATE POLICY ${q(`company_isolation_${table.tableName}`)} ON app.${name} USING (${policy}) WITH CHECK (${policy});`, '');
}

const indexSql = ['-- CONCURRENT indexes: execute outside a transaction.', 'SET search_path = app, public;', ''];
for (const index of tablesModel.indexContracts) {
  const table = tableById.get(index.tableId);
  indexSql.push(`CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX CONCURRENTLY IF NOT EXISTS ${q(index.indexName)} ON app.${q(table.tableName)} USING ${index.accessMethod} (${columns(index.columns)})${index.predicate ? ` WHERE ${index.predicate}` : ''};`);
}

const rollbackSql = ['-- DEVELOPMENT-ONLY compensation. Never execute against production without approved restore plan.', 'SET search_path = app, public;', ''];
for (const table of [...tables].reverse()) rollbackSql.push(`DROP TABLE IF EXISTS app.${q(table.tableName)} CASCADE;`);

const catalog = tables.map((table) => ({
  tableName: table.tableName,
  tableId: table.tableId,
  moduleCode: table.moduleCode,
  tableKind: table.tableKind,
  companyScope: table.companyScope,
  chineseName: dictionaryByTable.get(table.tableId)?.chineseName ?? table.tableName,
  primaryKey: table.primaryKey.columns,
  columns: table.columns.map((column) => ({
    name: column.columnName,
    type: column.dataType,
    nullable: column.nullable,
    identity: column.defaultValue === 'GENERATED_IDENTITY_PENDING_DDL',
    actorContext: column.defaultValue === 'CURRENT_ACTOR_CONTEXT_PENDING_DDL',
    hasDatabaseDefault: column.defaultValue !== null && !['系统推算', 'CHECK (value >= 0)', 'UNIQUE', 'FOREIGN KEY REFERENCES disbursement_voucher(id)'].includes(column.defaultValue),
    description: column.description,
    sensitivity: dictionary.find((entry) => entry.tableId === table.tableId && entry.columnName === column.columnName)?.sensitivityLevel ?? 'INTERNAL',
  })),
}));

const tsCatalog = `/* GENERATED FROM APPROVED DB-A2/DB-A3 MODELS. */\nexport interface ColumnCatalog { name: string; type: string; nullable: boolean; identity: boolean; actorContext: boolean; hasDatabaseDefault: boolean; description: string; sensitivity: string }\nexport interface TableCatalog { tableName: string; tableId: string; moduleCode: string; tableKind: string; companyScope: boolean; chineseName: string; primaryKey: string[]; columns: ColumnCatalog[] }\nexport const schemaCatalog = ${JSON.stringify(catalog, null, 2)} as const satisfies readonly TableCatalog[];\nexport const tableCatalogByName = new Map<string, TableCatalog>(schemaCatalog.map((table) => [table.tableName, table as TableCatalog]));\n`;

mkdirSync(join(appRoot, 'packages/database/src/generated'), { recursive: true });
mkdirSync(join(appRoot, 'migrations/rollback'), { recursive: true });
writeFileSync(join(appRoot, 'migrations/001_business_schema.sql'), `${schemaSql.join('\n')}\n`);
writeFileSync(join(appRoot, 'migrations/002_constraints_and_rls.sql'), `${constraintSql.join('\n')}\n`);
writeFileSync(join(appRoot, 'migrations/003_indexes_concurrently.sql'), `${indexSql.join('\n')}\n`);
writeFileSync(join(appRoot, 'migrations/rollback/001_business_schema_rollback.sql'), `${rollbackSql.join('\n')}\n`);
writeFileSync(join(appRoot, 'packages/database/src/generated/catalog.ts'), tsCatalog);

const report = {
  status: 'GENERATED_NOT_EXECUTED',
  sources: [tableSource, dictionarySource].map((file) => ({ file, sha256: digest(readFileSync(join(designRoot, file), 'utf8')) })),
  counts: {
    tables: tables.length,
    columns: tables.reduce((sum, table) => sum + table.columns.length, 0),
    primaryKeys: tables.length,
    uniqueConstraints: tablesModel.uniqueConstraintContracts.length,
    checkConstraints: tablesModel.checkConstraintContracts.length,
    indexes: tablesModel.indexContracts.length,
    rlsPolicies: tables.filter((table) => table.companyScope && table.columns.some((column) => column.columnName === 'company_code')).length,
  },
  normalizations,
  generatedFiles: ['migrations/001_business_schema.sql', 'migrations/002_constraints_and_rls.sql', 'migrations/003_indexes_concurrently.sql', 'migrations/rollback/001_business_schema_rollback.sql', 'packages/database/src/generated/catalog.ts'],
};
if (report.counts.tables !== 75 || report.counts.columns !== 979 || report.counts.indexes !== 252) throw new Error(`Model count mismatch: ${JSON.stringify(report.counts)}`);
writeFileSync(join(appRoot, 'schema-generation-report.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report.counts, null, 2));
