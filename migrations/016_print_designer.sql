-- Persist versioned canvas designs produced by the drag-and-drop label/form designer.
CREATE TABLE IF NOT EXISTS app_ops.print_template_design (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_code VARCHAR(16) NOT NULL CHECK (company_code IN ('THL','TGE')),
  template_id BIGINT NOT NULL,
  version INTEGER NOT NULL,
  canvas_width_mm NUMERIC(8,2) NOT NULL,
  canvas_height_mm NUMERIC(8,2) NOT NULL,
  elements JSONB NOT NULL,
  status VARCHAR(16) NOT NULL,
  created_by VARCHAR(32) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by VARCHAR(32),
  updated_at TIMESTAMPTZ,
  published_by VARCHAR(32),
  published_at TIMESTAMPTZ,
  CONSTRAINT uq_print_design_version UNIQUE (company_code, template_id, version),
  CONSTRAINT chk_print_design_canvas CHECK (canvas_width_mm > 0 AND canvas_height_mm > 0 AND canvas_width_mm <= 1000 AND canvas_height_mm <= 2000),
  CONSTRAINT chk_print_design_status CHECK (status IN ('draft','published','archived')),
  CONSTRAINT chk_print_design_elements CHECK (jsonb_typeof(elements) = 'array')
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_print_design_published
  ON app_ops.print_template_design (company_code, template_id)
  WHERE status = 'published';

CREATE INDEX IF NOT EXISTS idx_print_design_template
  ON app_ops.print_template_design (company_code, template_id, version);
