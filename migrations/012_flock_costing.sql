-- Auditable flock cost collection and moving book cost snapshots.
CREATE TABLE app_ops.flock_cost_entry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_code VARCHAR(16) NOT NULL CHECK (company_code IN ('THL','TGE')),
  batch_id BIGINT NOT NULL,
  cost_type VARCHAR(24) NOT NULL CHECK (cost_type IN ('chick','feed','vaccine','medication','labor','utility','other')),
  amount NUMERIC(16,2) NOT NULL CHECK (amount >= 0),
  source_type VARCHAR(32) NOT NULL,
  source_id VARCHAR(64) NOT NULL,
  incurred_on DATE NOT NULL,
  note VARCHAR(500),
  created_by VARCHAR(64) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (company_code,source_type,source_id,cost_type)
);
CREATE INDEX idx_ops_flock_cost_batch ON app_ops.flock_cost_entry (company_code,batch_id,incurred_on,id);

CREATE TABLE app_ops.flock_cost_snapshot (
  batch_id BIGINT NOT NULL,
  company_code VARCHAR(16) NOT NULL CHECK (company_code IN ('THL','TGE')),
  accumulated_cost NUMERIC(16,2) NOT NULL CHECK (accumulated_cost >= 0),
  remaining_flock NUMERIC(14,2) NOT NULL CHECK (remaining_flock >= 0),
  unit_cost NUMERIC(16,4) NOT NULL CHECK (unit_cost >= 0),
  calculated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (batch_id,company_code)
);
