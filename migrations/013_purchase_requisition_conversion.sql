-- Track the one-to-one conversion of an approved purchase requisition to a purchase order.
CREATE TABLE app_ops.purchase_requisition_conversion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_code VARCHAR(16) NOT NULL CHECK (company_code IN ('THL','TGE')),
  requisition_id BIGINT NOT NULL,
  purchase_order_id BIGINT NOT NULL,
  supplier_id BIGINT NOT NULL,
  material_id BIGINT NOT NULL,
  quantity NUMERIC(12,2) NOT NULL CHECK (quantity > 0),
  converted_by VARCHAR(64) NOT NULL,
  converted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (company_code, requisition_id),
  UNIQUE (company_code, purchase_order_id)
);

CREATE INDEX idx_ops_pr_conversion_supplier
  ON app_ops.purchase_requisition_conversion (company_code, supplier_id, converted_at);
