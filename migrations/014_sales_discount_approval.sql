-- Track sales discount requests and controlled approval before inventory allocation.
CREATE TABLE IF NOT EXISTS app_ops.sales_discount_approval (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_code VARCHAR(16) NOT NULL CHECK (company_code IN ('THL', 'TGE')),
  sales_order_id BIGINT NOT NULL,
  discount_percent NUMERIC(5,2) NOT NULL,
  reason VARCHAR(500) NOT NULL,
  status VARCHAR(16) NOT NULL,
  requested_by VARCHAR(32) NOT NULL,
  reviewed_by VARCHAR(32),
  reviewed_at TIMESTAMPTZ,
  review_note VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ,
  CONSTRAINT uq_sales_discount_order UNIQUE (company_code, sales_order_id),
  CONSTRAINT chk_sales_discount_percent CHECK (discount_percent > 0 AND discount_percent <= 25),
  CONSTRAINT chk_sales_discount_status CHECK (status IN ('pending', 'approved', 'rejected'))
);

CREATE INDEX IF NOT EXISTS idx_sales_discount_status
  ON app_ops.sales_discount_approval (company_code, status);
